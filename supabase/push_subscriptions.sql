create table if not exists public.push_subscriptions (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 endpoint text not null unique,
 p256dh text not null,
 auth text not null,
 created_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
drop policy if exists "Members manage own push subscriptions" on public.push_subscriptions;
create policy "Members manage own push subscriptions"
on public.push_subscriptions for all to authenticated
using (auth.uid()=user_id and exists(select 1 from public.profiles p where p.id=auth.uid() and p.approved=true))
with check (auth.uid()=user_id and exists(select 1 from public.profiles p where p.id=auth.uid() and p.approved=true));
