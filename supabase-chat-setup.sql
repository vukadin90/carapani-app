-- Podešavanje zajedničkog chat-a za Moto klub ČARAPANI
-- Pokrenuti jednom u Supabase Dashboard > SQL Editor > New query.

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.chat_messages enable row level security;

grant select, insert on public.chat_messages to authenticated;
grant usage, select on sequence public.chat_messages_id_seq to authenticated;

drop policy if exists "Approved members can read chat" on public.chat_messages;
create policy "Approved members can read chat"
on public.chat_messages for select
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.approved = true
  )
);

drop policy if exists "Approved members can send chat" on public.chat_messages;
create policy "Approved members can send chat"
on public.chat_messages for insert
to authenticated
with check (
  sender_id = auth.uid()
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.approved = true
  )
);

-- Omogućava da se nove poruke pojave odmah kod ostalih članova.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'chat_messages'
  ) then
    alter publication supabase_realtime add table public.chat_messages;
  end if;
end $$;
